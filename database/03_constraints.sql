
-- =====================================================
-- DATABRIDGE
-- STEP 03: CONSTRAINT VERIFICATION
-- MYSQL 8.0+
-- =====================================================

USE DataBridge;

-- 1. DISPLAY ALL PRIMARY KEY AND UNIQUE CONSTRAINTS

SELECT
    TABLE_NAME,
    CONSTRAINT_NAME,
    CONSTRAINT_TYPE
FROM INFORMATION_SCHEMA.TABLE_CONSTRAINTS
WHERE TABLE_SCHEMA = 'DataBridge'
AND CONSTRAINT_TYPE IN ('PRIMARY KEY', 'UNIQUE')
ORDER BY TABLE_NAME;


-- 2. DISPLAY ALL FOREIGN KEY RELATIONSHIPS

SELECT
    TABLE_NAME,
    COLUMN_NAME,
    CONSTRAINT_NAME,
    REFERENCED_TABLE_NAME,
    REFERENCED_COLUMN_NAME
FROM INFORMATION_SCHEMA.KEY_COLUMN_USAGE
WHERE TABLE_SCHEMA = 'DataBridge'
AND REFERENCED_TABLE_NAME IS NOT NULL
ORDER BY TABLE_NAME;


-- 3. DISPLAY CHECK CONSTRAINTS

SELECT
    tc.TABLE_NAME,
    tc.CONSTRAINT_NAME,
    cc.CHECK_CLAUSE
FROM INFORMATION_SCHEMA.TABLE_CONSTRAINTS tc
JOIN INFORMATION_SCHEMA.CHECK_CONSTRAINTS cc
    ON tc.CONSTRAINT_SCHEMA = cc.CONSTRAINT_SCHEMA
    AND tc.CONSTRAINT_NAME = cc.CONSTRAINT_NAME
WHERE tc.CONSTRAINT_SCHEMA = 'DataBridge'
AND tc.CONSTRAINT_TYPE = 'CHECK';


-- 4. DISPLAY NOT NULL COLUMNS

SELECT
    TABLE_NAME,
    COLUMN_NAME,
    COLUMN_TYPE,
    IS_NULLABLE
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA = 'DataBridge'
AND IS_NULLABLE = 'NO'
ORDER BY TABLE_NAME, ORDINAL_POSITION;


-- 5. VERIFY TABLE ENGINE

SELECT
    TABLE_NAME,
    ENGINE
FROM INFORMATION_SCHEMA.TABLES
WHERE TABLE_SCHEMA = 'DataBridge'
AND TABLE_TYPE = 'BASE TABLE';


-- 6. FINAL DATABASE SUMMARY

SELECT
    COUNT(*) AS Total_Tables
FROM INFORMATION_SCHEMA.TABLES
WHERE TABLE_SCHEMA = 'DataBridge'
AND TABLE_TYPE = 'BASE TABLE';
